#!/usr/bin/env python3
"""Render docs/workflow_comparison.md from the frozen v3 workflow matrix (PLAN DOC-08).

Every cell is derived from ``workflow_matrix.workflows`` in
``analysis/v3_validation/protocol.yaml`` (ids, roles, modes, reference arms, dataset
lists) and from ``workflow_matrix.status``. No performance number is printed: the
matrix has not been executed, and a quantitative cross-workflow claim needs a
``validated_v3`` artifact (DOC-10). ``--check`` exits 1 if the page is stale.

    python scripts/gen_workflow_comparison.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
PROTOCOL = ROOT / "analysis" / "v3_validation" / "protocol.yaml"
DOC = ROOT / "docs" / "workflow_comparison.md"

#: Five workflow families = the protocol's workflow tools grouped by strategy.
#: The 2.2.0 arms are a predecessor comparison (``predecessor_comparison_layer``), not a strategy.
FAMILIES: list[tuple[str, tuple[str, ...]]] = [
    ("ViralScan combined", ("W1_viralscan_combined",)),
    ("ViralScan exact-fragment two-step", ("W2_viralscan_two_step_star_exact_fragment",)),
    ("STARsolo", ("W3_starsolo_combined", "W4_starsolo_host_filter_two_step")),
    (
        "Traditional host subtraction",
        ("W5_traditional_subtraction_with_cb_umi", "W6_traditional_subtraction_without_cb_umi"),
    ),
    (
        "Dedicated viral scRNA-seq tools",
        tuple(
            f"W{n}{arm}_{tool}_{res}"
            for n, tool in ((7, "venus"), (8, "viral_track"), (9, "virtus"))
            for arm, res in (("a", "native"), ("b", "matched"))
        ),
    ),
]


def _load() -> dict[str, Any]:
    return yaml.safe_load(PROTOCOL.read_text(encoding="utf-8"))["workflow_matrix"]


def _attributes(w: dict[str, Any], status: str, n_all: int) -> tuple[list[str], list[str]]:
    """Strengths and limitations of one protocol workflow, from its own fields."""
    pros: list[str] = []
    cons: list[str] = []
    mode, arm = w["mode"], w.get("reference_resolution")
    if w["role"] == "primary":
        pros.append(f"The primary workflow; scheduled on all {n_all} frozen datasets.")
    if "combined-host-plus-virus" in mode:
        pros.append(
            "Host and viral features share one index, so host-virus ambiguity stays visible."
        )
    if "exact-fragment" in mode:
        pros.append("Exact fragment lineage between the host-removal and viral steps.")
    if mode.endswith("retaining-cb-umi"):
        pros.append("Retains cell barcode and UMI, so per-cell molecule counts exist.")
    if arm == "matched-accession-index":
        pros.append(
            "Matched-accession-index arm: shares viral sequences with ViralScan, the arm that carries cross-tool claims."
        )
    if arm == "native-published":
        pros.append("Native-published arm: measures the tool as its authors ship it.")
    if "published-default" in mode:
        pros.append("Run at published defaults, with no silent algorithm patch.")
    if "two-step" in mode or "subtract" in mode:
        cons.append(
            "Host reads are removed before viral alignment, so host-virus ambiguous reads are decided without the aligner seeing both (see the FAQ on combined versus two-step)."
        )
    if "discarding-cb-umi" in mode:
        cons.append("Discards cell barcode and UMI, so it cannot give per-cell molecule counts.")
    if arm == "native-published":
        cons.append(
            "Native arm uses a different reference; its numbers may not share a table with matched-arm numbers without disclosure."
        )
    if w["tool"] in {"venus", "viral-track", "virtus"}:
        cons.append(
            "Needs an isolated, digest-pinned third-party environment; failures are reported, not patched."
        )
    if status == "pending":
        cons.append(
            "Not yet executed under the frozen protocol, so there is no eligible result for it."
        )
    return pros, cons


def _merge(per_workflow: list[tuple[str, list[str]]]) -> str:
    """Join statements across a family, tagging each with the workflows it applies to."""
    merged: dict[str, list[str]] = {}
    for wid, texts in per_workflow:
        for text in texts:
            merged.setdefault(text, []).append(wid)
    every = {wid for wid, _ in per_workflow}
    return "<br>".join(
        text if set(ids) == every else f"{text} ({', '.join(f'`{i}`' for i in ids)})"
        for text, ids in merged.items()
    )


def render() -> str:
    matrix = _load()
    by_id = {w["id"]: w for w in matrix["workflows"]}
    status = matrix["status"]
    n_all = len({d for w in matrix["workflows"] for d in w["dataset_ids"]})
    lines = [
        "# Workflow comparison",
        "",
        "<!-- GENERATED by scripts/gen_workflow_comparison.py from analysis/v3_validation/protocol.yaml; do not edit. -->",
        "",
        "This page lists the five workflow families that the v3 validation protocol compares, with the",
        "strengths and limitations that follow from how each is defined there. It reports **no performance",
        "number and makes no ranking or superiority claim**: the workflow matrix has not been executed",
        f"(`workflow_matrix.status: {status}`), and a quantitative comparison needs a `validated_v3` artifact.",
        "See the [claim registry](https://github.com/mdmanurung/ViralScan/blob/main/claims/registry.json) entry `cross-tool-superiority`.",
        "",
        "| Workflow family | Protocol workflows | Strengths | Limitations |",
        "|---|---|---|---|",
    ]
    for name, ids in FAMILIES:
        wfs = [by_id[i] for i in ids]
        attrs = [(w["id"], *_attributes(w, status, n_all)) for w in wfs]
        pros = _merge([(wid, p) for wid, p, _ in attrs])
        cons = _merge([(wid, c) for wid, _, c in attrs])
        ids_cell = "<br>".join(
            f"`{i}` ({by_id[i]['role']}, {len(by_id[i]['dataset_ids'])} datasets)" for i in ids
        )
        lines.append(f"| {name} | {ids_cell} | {pros} | {cons} |")
    legacy = sorted(i for i in by_id if i.startswith("W10"))
    lines += [
        "",
        f"ViralScan 2.2.0 ({', '.join(f'`{i}`' for i in legacy)}) is a predecessor comparison, not a",
        "workflow strategy, and is scored on its UMI-deduplicated unique-mapping layer only.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not DOC.is_file() or DOC.read_text(encoding="utf-8") != text:
            print(f"{DOC} is stale; run scripts/gen_workflow_comparison.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
